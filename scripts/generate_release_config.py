"""Generate public native constants from the single release configuration."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
c=json.loads((root/'release-config.json').read_text())
assert re.fullmatch(r'[\w.-]+/[\w.-]+',c['repository'])
assert isinstance(c['versionCode'],int) and c['versionCode']>0
values={'REPOSITORY':c['repository'],'PUBLIC_KEY':c['manifestPublicKey'],'CERTIFICATE':c['apkCertificateSha256']}
text='package com.openrepertory.app;\n/** Public release configuration; generated by the build. No credentials. */\npublic final class UpdateConfig {\n'
for k,v in values.items():text+='    public static final String '+k+' = '+json.dumps(v)+';\n'
text+='    private UpdateConfig() {}\n}\n'
(root/'native/com/openrepertory/app/UpdateConfig.java').write_text(text)
